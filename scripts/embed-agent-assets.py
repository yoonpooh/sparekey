#!/usr/bin/env python3
"""Generate single-binary agent assets; --check detects stale generated sources."""
import argparse
from pathlib import Path

repo = Path(__file__).resolve().parents[1]
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--check', action='store_true')
args = parser.parse_args()
skill = (repo / 'skills/sparekey/SKILL.md').read_text()
header = '// Generated by scripts/embed-agent-assets.py. Do not edit by hand.\n'
outputs = {
    'Sources/sparekey/EmbeddedSkill.swift': header + 'enum EmbeddedSkill {\n    static let content = #"""\n' + skill.rstrip('\n') + '\n"""# + "\\n"\n}\n',

}
for relative, content in outputs.items():
    path = repo / relative
    if args.check:
        if not path.exists() or path.read_text() != content:
            raise SystemExit(f'Stale generated asset: {relative}; run scripts/embed-agent-assets.py')
    else:
        path.write_text(content)
print('Agent assets are current.' if args.check else 'Generated embedded agent assets.')
